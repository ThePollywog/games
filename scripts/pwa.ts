// Makes the web builds installable and playable offline. After each build it writes sw.js, a service
// worker that precaches every file the build produced, and, for a single-game build (VITE_GAME), a
// manifest named after that game with its own icon. The native apps never register the worker.
import { readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { join, relative, resolve, sep } from 'node:path';
import type { Plugin } from 'vite';

const GAME_NAMES: Record<string, string> = {
  'shipshape': 'Shipshape',
  'buoy-oh-buoy': 'Buoy Oh Buoy',
  'knots-and-bolts': 'Knots & Bolts',
  'hex-marks-the-spot': 'Hex Marks the Spot',
};

function filesIn(dir: string): string[] {
  return readdirSync(dir).flatMap((name) => {
    const path = join(dir, name);
    return statSync(path).isDirectory() ? filesIn(path) : [path];
  });
}

const worker = (version: string, files: string[]) => `// Generated by scripts/pwa.ts.
const CACHE = 'pollywog-${version}';
const PRECACHE = ${JSON.stringify(['./', ...files])};

self.addEventListener('install', (e) => {
  e.waitUntil(caches.open(CACHE).then((c) => c.addAll(PRECACHE)).then(() => self.skipWaiting()));
});

self.addEventListener('activate', (e) => {
  e.waitUntil(
    caches
      .keys()
      .then((keys) => Promise.all(keys.filter((k) => k.startsWith('pollywog-') && k !== CACHE).map((k) => caches.delete(k))))
      .then(() => self.clients.claim()),
  );
});

self.addEventListener('fetch', (e) => {
  const req = e.request;
  const url = new URL(req.url);
  if (req.method !== 'GET' || url.origin !== location.origin || url.pathname.includes('/api/')) return;
  if (req.mode === 'navigate') {
    // Other pages under this scope (a game's own build, the support page) look after themselves.
    if (url.pathname !== new URL(self.registration.scope).pathname && !url.pathname.endsWith('/index.html')) return;
    // The page: fresh when online, so updates arrive; the cached copy when offline.
    e.respondWith(
      fetch(req)
        .then((res) => {
          const copy = res.clone();
          if (res.ok) void caches.open(CACHE).then((c) => c.put('./', copy));
          return res;
        })
        .catch(() => caches.match('./', { ignoreSearch: true })),
    );
    return;
  }
  // Everything else is content-hashed or rarely changes: cache first.
  e.respondWith(
    caches.match(req).then(
      (hit) =>
        hit ??
        fetch(req).then((res) => {
          const copy = res.clone();
          if (res.ok) void caches.open(CACHE).then((c) => c.put(req, copy));
          return res;
        }),
    ),
  );
});
`;

export function pwa(): Plugin {
  let outDir = '';
  return {
    name: 'pollywog-pwa',
    apply: 'build',
    configResolved(config) {
      outDir = resolve(config.root, config.build.outDir);
    },
    closeBundle() {
      const game = process.env.VITE_GAME;
      if (game) {
        const path = join(outDir, 'manifest.webmanifest');
        const manifest = JSON.parse(readFileSync(path, 'utf8'));
        const name = GAME_NAMES[game] ?? game;
        Object.assign(manifest, {
          name,
          short_name: name,
          icons: [
            { src: `icons/${game}.png`, sizes: '192x192', type: 'image/png', purpose: 'any maskable' },
            { src: `icons/${game}-512.png`, sizes: '512x512', type: 'image/png', purpose: 'any maskable' },
          ],
        });
        writeFileSync(path, JSON.stringify(manifest, null, 2) + '\n');
      }
      const files = filesIn(outDir)
        .map((f) => relative(outDir, f).split(sep).join('/'))
        .filter((f) => f !== 'sw.js' && !f.startsWith('.') && f !== 'index.html');
      writeFileSync(join(outDir, 'sw.js'), worker(Date.now().toString(36), files.map((f) => `./${f}`)));
    },
  };
}
